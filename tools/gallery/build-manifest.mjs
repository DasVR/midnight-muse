// Rebuilds wireframe/gallery-data.js from the photos in wireframe/img/gallery/<category>/.
//
//   node tools/gallery/build-manifest.mjs
//
// Folder names are category ids: candlelit, coquette, y2k, love, grads, costume.
// Alt text already written for a photo (matched by its path) is kept; new
// photos get a placeholder alt to replace by hand. No dependencies: image
// sizes are read straight from the JPEG/PNG/WebP headers.
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../../wireframe");
const galleryDir = path.join(root, "img/gallery");
const outFile = path.join(root, "gallery-data.js");

const CATEGORIES = [
  { id: "candlelit", title: "Candlelit & Gothic" },
  { id: "coquette", title: "Lace & Coquette" },
  { id: "y2k", title: "Y2K" },
  { id: "love", title: "Love Stories" },
  { id: "grads", title: "Grads" },
  { id: "costume", title: "Costumes & Cosplay" },
];

function jpegSize(buf) {
  let i = 2;
  while (i < buf.length) {
    if (buf[i] !== 0xff) { i++; continue; }
    const marker = buf[i + 1];
    const len = buf.readUInt16BE(i + 2);
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
      return { h: buf.readUInt16BE(i + 5), w: buf.readUInt16BE(i + 7) };
    }
    i += 2 + len;
  }
  return null;
}

function imageSize(file) {
  const buf = fs.readFileSync(file);
  if (buf[0] === 0xff && buf[1] === 0xd8) return jpegSize(buf);
  if (buf.toString("ascii", 1, 4) === "PNG") return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
  if (buf.toString("ascii", 8, 12) === "WEBP") {
    const kind = buf.toString("ascii", 12, 16);
    if (kind === "VP8X") return { w: 1 + buf.readUIntLE(24, 3), h: 1 + buf.readUIntLE(27, 3) };
    if (kind === "VP8L") { const b = buf.readUInt32LE(21); return { w: 1 + (b & 0x3fff), h: 1 + ((b >> 14) & 0x3fff) }; }
    if (kind === "VP8 ") return { w: buf.readUInt16LE(26) & 0x3fff, h: buf.readUInt16LE(28) & 0x3fff };
  }
  return null;
}

// Keep any alt text already written in the current manifest.
const existingAlt = new Map();
if (fs.existsSync(outFile)) {
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(outFile, "utf8"), sandbox);
  for (const p of (sandbox.window.GALLERY || { photos: [] }).photos) existingAlt.set(p.src, p.alt);
}

if (!fs.existsSync(galleryDir)) {
  console.error(`No ${path.relative(process.cwd(), galleryDir)} folder yet. Create one subfolder per category and add photos.`);
  process.exit(1);
}

const photos = [];
const skipped = [];
for (const cat of CATEGORIES) {
  const dir = path.join(galleryDir, cat.id);
  if (!fs.existsSync(dir)) continue;
  for (const name of fs.readdirSync(dir).sort()) {
    if (name === "thumbs") continue;
    if (!/\.(jpe?g|png|webp)$/i.test(name)) { if (!name.startsWith(".")) skipped.push(`${cat.id}/${name}`); continue; }
    const src = `img/gallery/${cat.id}/${name}`;
    const size = imageSize(path.join(dir, name));
    if (!size) { skipped.push(`${cat.id}/${name} (unreadable)`); continue; }
    const photo = { src, w: size.w, h: size.h, category: cat.id, alt: existingAlt.get(src) || `Photograph by Dani, ${cat.title}.` };
    // Small copies for the pinned board live in thumbs/ under the same name.
    if (fs.existsSync(path.join(dir, "thumbs", name))) photo.thumb = `img/gallery/${cat.id}/thumbs/${name}`;
    photos.push(photo);
  }
}

const unknown = fs.readdirSync(galleryDir).filter((d) => !d.startsWith(".") && !CATEGORIES.some((c) => c.id === d));
const header = "// Photographs shown inside the wardrobe. Generated by tools/gallery/build-manifest.mjs.\n";
fs.writeFileSync(outFile, header + "window.GALLERY = " + JSON.stringify({ categories: CATEGORIES, photos }, null, 2) + ";\n");

const counts = Object.fromEntries(CATEGORIES.map((c) => [c.id, photos.filter((p) => p.category === c.id).length]));
console.log(`Wrote ${photos.length} photos to ${path.relative(process.cwd(), outFile)}`, counts);
if (unknown.length) console.warn("Ignored folders that aren't categories:", unknown.join(", "));
if (skipped.length) console.warn("Skipped files:", skipped.join(", "));
const placeholders = photos.filter((p) => p.alt.startsWith("Photograph by Dani,")).length;
if (placeholders) console.warn(`${placeholders} photos still have placeholder alt text.`);
